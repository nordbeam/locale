import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { compileProject } from '../dist/compiler.js';
import { writeProject } from '../dist/project.js';
import { quote } from '../dist/codegen.js';
import { decode, encode } from '@jridgewell/sourcemap-codec';

export async function temporary(t) {
  const path = await mkdtemp(join(tmpdir(), 'nordbeam-i18n-'));
  // This hook runs before hooks the test registers later, such as closing a Vite
  // server whose optimizer may still be writing node_modules/.vite. Retry instead
  // of failing, and never throw: a throwing hook skips the later ones, and an
  // unclosed server keeps the test file running.
  t.after(() => rm(path, { recursive: true, force: true, maxRetries: 10, retryDelay: 50 }).catch(() => undefined));
  return path;
}
export async function compiled(t, options) {
  const dir = await temporary(t);
  const result = compileProject(options);
  await writeProject(result, dir);
  return { ...result, dir, load: async path => import(pathToFileURL(join(dir, path)).href) };
}

export async function waitFor(check, message, timeout = 8000) {
  const start = Date.now();
  for (;;) {
    if (await check()) return;
    if (Date.now() - start > timeout) throw new Error(message);
    await new Promise(resolve => setTimeout(resolve, 25));
  }
}

// Historical byte-parity fixtures predate the mapped formatter memo. Remove
// only that exact generated declaration and the exact NumberFormat/PluralRules
// wrapper so legacy comparisons retain all message bodies, helper identities,
// projections and maps. Current-versus-current comparisons must not use this.
const formatterMemo = 'const $memo=f=>{const keys=[],values=[];return v=>{if(typeof v!=="number")return f(v);const slot=v&63;if(Object.is(keys[slot],v))return values[slot];const next=f(v);keys[slot]=v;values[slot]=next;return next;}};';
// Integer fast paths wrap the same memoized Intl selector in one-line closures.
// Frozen baselines predate them, so restore the exact previous declarations.
const legacyFastPathNumber = /^let (\$f\d+)Cache;const \1=\/\*#__PURE__\*\/\(s=>v=>Number\.isInteger\(v\)&&v>=0&&v<1000&&!Object\.is\(v,-0\)\?""\+v:s\(v\)\)\((\/\*#__PURE__\*\/\$memo\(v=>.*)\);$/gm;
const legacyFastPathPlural = /^(let \$f\d+Cache;)const (\$f\d+)=\/\*#__PURE__\*\/\(\(k,i,s\)=>v=>.*?\)\(\[[^\]]*\],"\d+",(\/\*#__PURE__\*\/\$memo\(v=>.*)\);$/gm;
// Generated files name their build mode and catalogs. Frozen baselines carry the original one-line header.
const legacyGeneratedHeader = /^\/\/ Generated by Nordbeam Locale \((?:development|production) build\)\. Do not edit: change [^\n]*?\/\*\.json and run `nordbeam-locale`\./m;
export function normalizeLegacyFormatterCacheOutput(fastPathSource) {
  const source = fastPathSource.replace(legacyGeneratedHeader, '// Generated by Nordbeam Locale. Do not edit.')
    .replace(legacyFastPathNumber, (_, id, memo) => `let ${id}Cache;const ${id}=${memo};`)
    .replace(legacyFastPathPlural, (_, cache, id, memo) => `${cache}const ${id}=${memo};`);
  // Named public declaration aliases can add unmapped trailing lines without
  // moving any catalog mapping. Ignore only those terminal separators when a
  // fixture compares against the pre-alias declaration-map shape.
  if (source.startsWith('{"version":3,') && source.includes('"mappings":')) {
    return source.replace(/;+(?="}\n?$)/, '');
  }
  if (source.includes('declare const $m')) return normalizeLegacyDeclarations(source.replace('// Generated by Nordbeam Locale. Do not edit.', '// Generated by fasti18n. Do not edit.'));
  // Development output now rejects invalid Dates with locale/message context;
  // frozen baselines predate that guard.
  const withoutBrand = source.replace('// Generated by Nordbeam Locale. Do not edit.', '// Generated by fasti18n. Do not edit.')
    .replace(/if\(!Number\.isFinite\(\+[^)]*\)\)throw new TypeError\([^;]*?must be a valid Date[^;]*?\);/g, '');
  const withoutMemo = withoutBrand.replace(`${formatterMemo}\n`, '');
  const formatters = withoutMemo.replace(/^let (\$f\d+)Cache;const \1=\/\*#__PURE__\*\/\$memo\(v=>(.*)\);$/gm,
    (line, id, expression) => /new Intl\.(?:NumberFormat|PluralRules)\(/.test(expression)
      ? `let ${id}Cache;const ${id}=v=>${expression};`
      : line);
  const staticAliases = formatters.replace(/const messages=\/\*#__PURE__\*\/\(\(\)=>\{const messages=(\{__proto__:null,.*?)\};(?:const \$nest=.*?\n)?Object\.defineProperty.*?\nreturn messages;\}\)\(\);export default messages;/gs,
    (_, object) => source.includes('export {$m') ? `const messages=${object}};export default messages;` : `export default ${object}};`);
  return staticAliases.replace(/const \$nested=.*?\nconst messages=\/\*#__PURE__\*\/\$nested\((\{__proto__:null,.*\})\);export default messages;/gs,
    (_, object) => source.includes('export {$m') ? `const messages=${object};export default messages;` : `export default ${object};`);
}
// The historical comparison compilers emitted string-literal export aliases.
// Current declarations intentionally use TS 5.5-safe direct aliases and keep
// unsafe IDs in the default object. Reconstruct the old spelling only for
// byte-parity comparisons; product output is never passed through this.
// Hover text precedes each declaration on its own line. Frozen declarations
// predate it, so remove it and map generated columns back on the same line.
const hoverText = /\/\*\*(?:(?!\*\/).)*\*\/ (?=declare const |readonly )/g;
function normalizeLegacyDeclarations(source) {
  let normalized = source.replace(hoverText, '');
  const ids = new Map();
  if (source.includes('declare const $m')) {
    for (const [, raw, name] of source.matchAll(/readonly ("(?:[^"\\]|\\.)*"): typeof (\$m\d+);/g)) ids.set(name, JSON.parse(raw));
    normalized = normalized.replace(/declare const (\$m\d+): ([^\n]+);(?:\nexport \{\1 as (?:[A-Za-z_$][A-Za-z0-9_$]*|"(?:[^"\\]|\\.)*")\};)?/g,
      (line, name, signature) => {
        const id = ids.get(name);
        return id !== undefined && id !== 'then' && id !== 'default' && !/[\uD800-\uDFFF]/u.test(id)
          ? `declare const ${name}: ${signature};\nexport {${name} as ${quote(id)}};`
          : `declare const ${name}: ${signature};`;
      });
  }
  return normalized
    .replace(/interface \$Flat extends ([^\n{]*?) \{\}\ntype \$Messages = \{\[Key in keyof \$Flat\]: \$Flat\[Key\]\};\n/,
      (_, bases) => `type $Messages = ${bases.split(', ').join(' & ')};\n`)
    .replace(/type \$FlatMessages = \{([\s\S]*?)\n\};\ntype \$Nest<[\s\S]*?declare const messages: Messages;\nexport default messages;/,
      'declare const messages: {$1\n};\nexport default messages;')
    .replace(/export type Messages = \{([\s\S]*?)\n\};\ndeclare const messages: Messages;\nexport default messages;/,
      'declare const messages: {$1\n};\nexport default messages;')
    .replace(/export type Messages=\$Messages;\ndeclare const messages: Messages;\nexport default messages;/,
      'declare const messages: { readonly [Key in keyof $Messages]: $Messages[Key] };\nexport default messages;');
}
// Frozen maps predate hover text. Each generated line's columns move left by the
// hover text removed before them, using the same declaration the map describes.
export function normalizeLegacyDeclarationMap(map, declaration) {
  const parsed = JSON.parse(map);
  const lines = declaration.split('\n');
  parsed.mappings = encode(decode(parsed.mappings).map((segments, line) => {
    const removed = [...lines[line].matchAll(hoverText)].map(match => [match.index, match[0].length]);
    if (!removed.length) return segments;
    return segments.map(([column, ...rest]) => [column - removed.reduce((sum, [index, length]) => index + length <= column ? sum + length : sum, 0), ...rest]);
  }));
  return JSON.stringify(parsed) + '\n';
}
export function normalizeLegacyProject(project) {
  const nestedApi = source => source
    .replace(/^import type \{MessageId,SelectedMessages\} from "\.\/messages\.js";\n/m, '')
    .replace(/export interface LoadedSelection<Key extends MessageId> \{ readonly locale: Locale; readonly messages: SelectedMessages<Key> \}\nexport declare function selectMessages<const Keys extends readonly \[MessageId, \.\.\.MessageId\[\]\]>\(\.\.\.keys: Keys\): \(locale: Locale\) => Promise<LoadedSelection<Keys\[number\]>>;/,
      'export interface LoadedSelection<Key extends keyof Messages> { readonly locale: Locale; readonly messages: Pick<Messages, Key> }\nexport declare function selectMessages<const Keys extends readonly [keyof Messages, ...(keyof Messages)[]]>(...keys: Keys): (locale: Locale) => Promise<LoadedSelection<Keys[number]>>;')
    .replace(/const \$namespace=.*?\nconst \$nested=.*?\n/s, '')
    .replace(/\$nested\(messages,keys\);/g, '')
    .replace(/const messages=\/\*#__PURE__\*\/\(\(\)=>\{const messages=(\{__proto__:null,.*?)\};(?:const \$nest=.*?\n)?Object\.defineProperty.*?\nreturn messages;\}\)\(\);export default messages;/gs,
      'const messages=$1};export default messages;')
    .replace(/type \$FlatMessages = \{([\s\S]*?)\n\};\ntype \$Nest<[\s\S]*?declare const messages: Messages;\nexport default messages;/,
      'declare const messages: {$1\n};\nexport default messages;')
    .replace(/export type Messages = \{([\s\S]*?)\n\};\ndeclare const messages: Messages;\nexport default messages;/,
      'declare const messages: {$1\n};\nexport default messages;')
    .replace(/type \$Nest<[\s\S]*?declare const messages: Messages;\nexport default messages;/,
      'declare const messages: { readonly [Key in keyof $Messages]: $Messages[Key] };\nexport default messages;')
    .replace(/export type Messages=\$Messages;\ndeclare const messages: Messages;\nexport default messages;/,
      'declare const messages: { readonly [Key in keyof $Messages]: $Messages[Key] };\nexport default messages;');
  const files = Object.assign(Object.create(Object.getPrototypeOf(project.files)), Object.fromEntries(Object.entries(project.files)
    // Compact full-catalog modules are a new internal representation. Frozen
    // compiler baselines predate them, so legacy comparisons remove only those
    // private files and restore the old loader specifier. Current-versus-current
    // comparisons continue to exercise the complete output byte-for-byte.
    .filter(([file]) => !file.includes('internal/locales/'))
    .map(([file, source]) => [
      file,
      /(?:^|\/)locales\/[^/]+\.js$/.test(file)
        ? nestedApi(normalizeLegacyFormatterCacheOutput(source))
        : file.endsWith('.d.ts.map')
          ? normalizeLegacyFormatterCacheOutput(normalizeLegacyDeclarationMap(source, project.files[file.slice(0, -'.map'.length)]))
        : file.endsWith('index.js')
          ? nestedApi(normalizeLegacyFormatterCacheOutput(source).replaceAll('./internal/locales/', './locales/'))
          : nestedApi(normalizeLegacyDeclarations(normalizeLegacyFormatterCacheOutput(source))),
    ])));
  return {
    ...project,
    files,
  };
}
