// JSON quoting protects source code and script-element embedding.
export const quote = (value) => JSON.stringify(value).replace(/[<\u2028\u2029]/g, character => character === '<' ? '\\u003c' : character === '\u2028' ? '\\u2028' : '\\u2029');
export const header = '// Generated by fasti18n. Do not edit.\n';
/** Rewrite internal identifiers in compiler-owned code, skipping JSON strings. */
export function rewriteGeneratedIdentifiers(source, rename) {
    return source.replace(/"(?:[^"\\]|\\.)*"|(\$f\d+(?:Cache)?|\$literal|\$parts)\b/g, (token, identifier) => identifier ? rename(identifier) : token);
}
/** Substitute compiler-owned text parameters without touching quoted user data. */
export function substituteTextParameters(source, values) {
    return source.replace(/"(?:[^"\\]|\\.)*"|\$s(\d+)\b/g, (token, index) => index === undefined ? token : quote(values[Number(index)]));
}
