// Most generated IDs and text need no escaping. Keep JSON's full behavior for
// other values, controls and UTF-16 surrogates, plus script-element protection.
const requiresEscaping = /["\\<\u0000-\u001f\u2028\u2029\ud800-\udfff]/;
export const quote = (value: unknown): string => typeof value === 'string' && !requiresEscaping.test(value)
  ? '"' + value + '"'
  : JSON.stringify(value).replace(/[<\u2028\u2029]/g,
    character => character === '<' ? '\\u003c' : character === '\u2028' ? '\\u2028' : '\\u2029');
export const header = '// Generated by Nordbeam Locale. Do not edit.\n';
// Generated JavaScript is intentionally untyped implementation output. Keep
// TypeScript checkJs consumers from treating compiler-owned helper parameters
// as application code, while declarations continue to be checked normally.
export const jsHeader = '// @ts-nocheck\n' + header;

/** Rewrite internal identifiers in compiler-owned code, skipping JSON strings. */
export function rewriteGeneratedIdentifiers(source: string, rename: (identifier: string) => string): string {
  return source.replace(/"(?:[^"\\]|\\.)*"|(\$f\d+(?:Cache)?|\$literal|\$parts|\$memo)\b/g,
    (token: string, identifier: string | undefined) => identifier ? rename(identifier) : token);
}

/** Substitute compiler-owned text parameters without touching quoted user data.
 * Fold a following quoted constant too, so inlined validation labels match
 * direct error strings. Joining JSON string payloads preserves their escapes.
 */
export function substituteTextParameters(source: string, values: readonly string[]): string {
  if (source.startsWith('{const $c')) source = '(()=>'+source+')()';
  const substituted = source.replace(/"(?:[^"\\]|\\.)*"|\$s(\d+)\b(?:\+("(?:[^"\\]|\\.)*"))?/g,
    (token: string, index: string | undefined, suffix: string | undefined) => {
      if (index === undefined) return token;
      const value = quote(values[Number(index)]);
      return suffix === undefined ? value : value.slice(0, -1) + suffix.slice(1);
    });
  if (!substituted.startsWith('(()=>{const $c')) return substituted;
  // A one-off projection can evaluate compiler-owned string initializers at
  // build time and recover exactly the direct, folded function expression.
  let body = substituted.slice('(()=>{'.length);
  const constants = new Map<string, string>();
  for (;;) {
    const declaration = /^const (\$c\d+)=("(?:[^"\\]|\\.)*"(?:\+"(?:[^"\\]|\\.)*")*);/.exec(body);
    if (!declaration) break;
    constants.set(declaration[1]!, [...declaration[2]!.matchAll(/"(?:[^"\\]|\\.)*"/g)].map(match => JSON.parse(match[0]) as string).join(''));
    body = body.slice(declaration[0].length);
  }
  if (!body.startsWith('return ') || !body.endsWith(';})()')) throw new Error('Invalid generated literal initializers.');
  return body.slice('return '.length, -';})()'.length).replace(/"(?:[^"\\]|\\.)*"|(\$c\d+)\b/g,
    (token: string, identifier: string | undefined) => identifier === undefined ? token : quote(constants.get(identifier)));
}

/** Rewrite the generated header's line in place (no added lines, so declaration
 * maps keep their positions) to name the build mode and the edit path. Files
 * without the compiler header, such as package.json and source maps, pass through. */
export function markGenerated(source: string, development: boolean, catalogs: string): string {
  // catalogs is the project-relative catalog directory.
  const line = `// Generated by Nordbeam Locale (${development ? 'development' : 'production'} build). Do not edit: change ${catalogs}/*.json and run \`nordbeam-locale\`.`;
  const tsCheck = '// @ts-nocheck\n';
  // The header's trailing newline stays in place, so only the header text is replaced.
  if (source.startsWith(header)) return line + source.slice(header.length - 1);
  if (source.startsWith(jsHeader)) return tsCheck + line + source.slice(jsHeader.length - 1);
  return source;
}
